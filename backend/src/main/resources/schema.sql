-- esquema de datos
CREATE TABLE IF NOT EXISTS rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(120) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(100) NOT NULL,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    acepta_tratamiento_datos BOOLEAN NOT NULL,
    estado VARCHAR(12) NOT NULL CHECK (estado IN ('ACTIVA', 'INACTIVA', 'RESTRINGIDA')),
    fecha_registro TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuario (id_usuario),
    id_rol BIGINT NOT NULL REFERENCES rol (id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE IF NOT EXISTS codigo_recuperacion (
    id_codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario (id_usuario),
    codigo VARCHAR(10) NOT NULL,
    expira_en TIMESTAMP NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS politica_cancelacion (
    id_politica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL UNIQUE,
    dias_anticipacion INT NOT NULL CHECK (dias_anticipacion >= 0),
    porcentaje_devolucion INT NOT NULL CHECK (porcentaje_devolucion BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS publicacion (
    id_publicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anfitrion BIGINT NOT NULL REFERENCES usuario (id_usuario),
    id_politica BIGINT REFERENCES politica_cancelacion (id_politica),
    titulo VARCHAR(150) NOT NULL,
    descripcion VARCHAR(2000),
    ciudad VARCHAR(60) NOT NULL,
    direccion VARCHAR(150),
    tipo_alojamiento VARCHAR(40) NOT NULL,
    capacidad INT NOT NULL CHECK (capacidad > 0),
    precio_noche NUMERIC(12, 2) NOT NULL CHECK (precio_noche > 0),
    tarifa_limpieza NUMERIC(12, 2) NOT NULL DEFAULT 0,
    reglas VARCHAR(1000),
    modo_reserva VARCHAR(20) NOT NULL CHECK (modo_reserva IN ('INMEDIATA', 'CON_APROBACION')),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR', 'PENDIENTE_REVISION', 'ACTIVA', 'PAUSADA', 'BLOQUEADA'))
);

CREATE TABLE IF NOT EXISTS imagen_publicacion (
    id_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion BIGINT NOT NULL REFERENCES publicacion (id_publicacion),
    url VARCHAR(300) NOT NULL,
    orden INT NOT NULL
);

CREATE TABLE IF NOT EXISTS servicio_adicional (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion BIGINT NOT NULL REFERENCES publicacion (id_publicacion),
    nombre VARCHAR(60) NOT NULL,
    costo NUMERIC(12, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS periodo_disponible (
    id_periodo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publicacion BIGINT NOT NULL REFERENCES publicacion (id_publicacion),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS reserva (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_huesped BIGINT NOT NULL REFERENCES usuario (id_usuario),
    id_publicacion BIGINT NOT NULL REFERENCES publicacion (id_publicacion),
    fecha_llegada DATE NOT NULL,
    fecha_salida DATE NOT NULL,
    numero_huespedes INT NOT NULL CHECK (numero_huespedes > 0),
    tarifa_base NUMERIC(12, 2) NOT NULL,
    cargo_limpieza NUMERIC(12, 2) NOT NULL,
    cargo_servicio NUMERIC(12, 2) NOT NULL,
    descuentos NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    clave_idempotencia VARCHAR(60) NOT NULL UNIQUE,
    estado VARCHAR(25) NOT NULL CHECK (estado IN ('PENDIENTE_APROBACION', 'PENDIENTE_PAGO', 'CONFIRMADA',
        'RECHAZADA', 'CANCELADA', 'COMPLETADA', 'EN_REVISION_MANUAL')),
    fecha_creacion TIMESTAMP NOT NULL,
    CHECK (fecha_salida > fecha_llegada)
);

CREATE TABLE IF NOT EXISTS reserva_servicio (
    id_reserva BIGINT NOT NULL REFERENCES reserva (id_reserva),
    id_servicio BIGINT NOT NULL REFERENCES servicio_adicional (id_servicio),
    costo_aplicado NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (id_reserva, id_servicio)
);

CREATE TABLE IF NOT EXISTS pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva BIGINT NOT NULL UNIQUE REFERENCES reserva (id_reserva),
    monto NUMERIC(12, 2) NOT NULL,
    referencia_pasarela VARCHAR(60) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS cancelacion (
    id_cancelacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva BIGINT NOT NULL UNIQUE REFERENCES reserva (id_reserva),
    id_usuario BIGINT NOT NULL REFERENCES usuario (id_usuario),
    motivo VARCHAR(200) NOT NULL,
    valor_devolucion NUMERIC(12, 2) NOT NULL,
    estado_final VARCHAR(20) NOT NULL,
    fecha TIMESTAMP NOT NULL
);

-- registro de reportes
CREATE TABLE IF NOT EXISTS reporte (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_administrador BIGINT NOT NULL REFERENCES usuario (id_usuario),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('USUARIOS', 'PUBLICACIONES', 'RESERVAS', 'INGRESOS', 'DEMANDA')),
    formato VARCHAR(10) NOT NULL,
    fecha_solicitud TIMESTAMP NOT NULL
);
